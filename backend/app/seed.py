def seed_if_empty(db: Session) -> None:
    existing = db.execute(select(func.count(Ward.id))).scalar_one()
    if not existing:
        seed(db)
    else:
        seed_reference_data(db, include_demo_fleet=True)
    seed_users(db)


def seed_reference_data(db: Session, *, include_demo_fleet: bool) -> None:
    """Upsert Pune demo zones and (when requested) the simulator's test devices."""
    existing_wards = {ward.code: ward for ward in db.execute(select(Ward)).scalars().all()}
    for ward_data in WARDS:
        current = existing_wards.get(ward_data["code"])
        geometry = box_wkt(ward_data["bounds"])
        if current is None:
            db.add(Ward(code=ward_data["code"], name=ward_data["name"], geom_wkt=geometry))
        else:
            # Ward codes stayed stable across the city demo change. Updating their labels
            # and bounds migrates an existing empty/demo database away from Bengaluru.
            current.name = ward_data["name"]
            current.geom_wkt = geometry
            db.add(current)

    if include_demo_fleet:
        existing_vehicles = {vehicle.label: vehicle for vehicle in db.execute(select(Vehicle)).scalars().all()}
        for label, route in FLEET:
            if label not in existing_vehicles:
                db.add(Vehicle(fleet_id="TRANSIT-01", label=label, route_id=route))

    db.commit()


def _remove_legacy_bengaluru_demo(db: Session) -> int:
    """Remove only incidents generated by the old synthetic Bengaluru seed.

    Non-demo incidents are preserved. Audit history is not deleted; a migration event
    records what was refreshed. This runs only when the operator explicitly enables
    DEMO_DATA_ENABLED in a demo deployment.
    """
    legacy_ids = list(db.execute(
        select(Incident.id).where(Incident.source_event_id.like("demo-edge-%"))
    ).scalars().all())
    if not legacy_ids:
        return 0

    order_ids = select(WorkOrder.id).where(WorkOrder.incident_id.in_(legacy_ids))
    db.execute(delete(WorkOrderEvidence).where(WorkOrderEvidence.work_order_id.in_(order_ids)))
    db.execute(delete(WorkOrder).where(WorkOrder.incident_id.in_(legacy_ids)))
    db.execute(delete(IncidentVerification).where(IncidentVerification.incident_id.in_(legacy_ids)))
    # Old seed events all used the demo-edge prefix. Delete their receipts so they
    # cannot point to removed sample incidents. Genuine incident receipts are retained.
    db.execute(delete(EventReceipt).where(
        EventReceipt.event_id.like("demo-edge-%") | EventReceipt.incident_id.in_(legacy_ids)
    ))
    db.execute(update(Incident).where(Incident.merged_into_id.in_(legacy_ids)).values(merged_into_id=None))
    db.execute(delete(Incident).where(Incident.id.in_(legacy_ids)))
    record_audit(
        db, actor=None, actor_label="system-demo-migration", action="demo.legacy_bengaluru_data_replaced",
        entity_type="dataset", entity_id="pune-demo",
        details={"legacy_demo_incidents_removed": len(legacy_ids), "replacement_city": "Pune, Maharashtra"},
        commit=False,
    )
    db.commit()
    return len(legacy_ids)


def seed_users(db: Session) -> None:
    if settings.is_production and settings.supabase_url:
        # These are operational shadow users for foreign keys, audit logs and assignment.
        # Passwords are random/unusable; Supabase Auth is the only public login provider.
        accounts = []
        for email, role in settings.supabase_role_by_email.items():
            username = email.split("@", 1)[0]
            accounts.append((username, secrets.token_urlsafe(48), role))
    elif settings.is_production:
        password = settings.bootstrap_engineer_password
        if not password:
            raise RuntimeError("BOOTSTRAP_ENGINEER_PASSWORD is required when Supabase Auth is not configured")
        accounts = [("engineer", password, "engineer")]
    else:
        # Local-only starter credentials; change them before exposing a development deployment.
        accounts = [
            ("engineer", "engineer123", "engineer"),
            ("worker", "worker123", "worker"),
        ]
    changed = False
    for username, password, role in accounts:
        exists = db.execute(select(User).where(User.username == username)).scalar_one_or_none()
        if not exists:
            db.add(User(username=username, password_hash=hash_password(password), role=role, is_active=True))
            changed = True
        elif exists.role != role:
            exists.role = role
            exists.token_version += 1
            db.add(exists)
            changed = True
    if changed:
        db.commit()


def seed(db: Session) -> None:
    seed_reference_data(db, include_demo_fleet=not settings.is_production)
    if settings.is_production and not settings.demo_data_enabled:
        return
    _seed_demo_incidents(db)


def seed_demo_data_if_empty(db: Session) -> None:
    """Provision the illustrative Pune demo dataset, without replacing genuine reports."""
    seed_reference_data(db, include_demo_fleet=True)
    _remove_legacy_bengaluru_demo(db)
    pune_demo_count = db.execute(
        select(func.count(Incident.id)).where(Incident.source_event_id.like("demo-pune-edge-%"))
    ).scalar_one()
    if not pune_demo_count:
        # DEMO_DATA_ENABLED is an explicit operator opt-in. Seed Pune samples even
        # if real event records also exist; only old synthetic Bengaluru rows are removed.
        _seed_demo_incidents(db)
    seed_users(db)
    _seed_demo_work_orders(db)


def _seed_demo_work_orders(db: Session) -> None:
    """Create a small, clearly synthetic work-order lifecycle for demo navigation."""
    existing = db.execute(
        select(func.count(WorkOrder.id))
        .join(Incident, WorkOrder.incident_id == Incident.id)
        .where(Incident.source_event_id.like("demo-pune-edge-%"))
    ).scalar_one()
    if existing:
        return

    engineer = db.execute(select(User).where(User.username == "engineer")).scalar_one_or_none()
    worker = db.execute(select(User).where(User.username == "worker")).scalar_one_or_none()
    if not engineer or not worker:
        return

    candidates = list(db.execute(
        select(Incident)
        .where(
            Incident.source_event_id.like("demo-pune-edge-%"),
            Incident.merged_into_id.is_(None),
            Incident.status == "open",
            Incident.severity.in_(["critical", "moderate"]),
        )
        .order_by(Incident.depth_mm.desc())
        .limit(4)
    ).scalars().all())
    if len(candidates) < 4:
        return

    # A report under review with no ticket yet.
    review_incident(db, candidates[0], engineer, "DEMO ONLY: sample Pune defect awaiting dispatch.")

    # A dispatched ticket assigned to the Field Crew account.
    review_incident(db, candidates[1], engineer, "DEMO ONLY: sample Pune repair approved.")
    dispatched = auto_dispatch(db, candidates[1], engineer)
    update_work_order(db, dispatched, WorkOrderUpdateIn(assigned_to_id=worker.id), engineer)

    # An active repair, useful for demonstrating Worker progress actions.
    review_incident(db, candidates[2], engineer, "DEMO ONLY: sample Pune repair approved.")
    active = auto_dispatch(db, candidates[2], engineer)
    update_work_order(
        db, active,
        WorkOrderUpdateIn(assigned_to_id=worker.id, status="in_progress"),
        engineer,
    )

    # A completed sample repair waiting for the independent verification queue.
    review_incident(db, candidates[3], engineer, "DEMO ONLY: sample Pune repair approved.")
    completed = auto_dispatch(db, candidates[3], engineer)
    update_work_order(
        db, completed,
        WorkOrderUpdateIn(assigned_to_id=worker.id, status="in_progress"),
        engineer,
    )
    update_work_order(
        db, completed,
        WorkOrderUpdateIn(
            status="resolved",
            completion_notes="DEMO ONLY: illustrative patch repair marked complete; awaiting independent bus checks.",
        ),
        engineer,
    )


def _seed_demo_incidents(db: Session) -> None:
    rng = random.Random(42)
    now = utcnow()
    severities = (
        ["critical"] * 18
        + ["moderate"] * 32
        + ["clear"] * 28
    )
    rng.shuffle(severities)

    for idx, severity in enumerate(severities):
        route_id = rng.choice(list(ROUTES))
        t = rng.random()
        lon, lat = interpolate_route(route_id, t)
        lon += rng.uniform(-0.004, 0.004)
        lat += rng.uniform(-0.004, 0.004)
        depth = {
            "critical": rng.uniform(42, 95),
            "moderate": rng.uniform(18, 39),
            "clear": rng.uniform(2, 12),
        }[severity]
        vehicle = rng.choice([item for item in FLEET if item[1] == route_id])
        ts = now - timedelta(hours=rng.uniform(0.2, 72))
        payload = EdgeEventIn(
            event_id=f"demo-pune-edge-{uuid.uuid4().hex[:12]}",
            vehicle_label=vehicle[0],
            route_id=route_id,
            timestamp=ts,
            lon=lon,
            lat=lat,
            speed_kmh=rng.uniform(12, 48),
            engine_status=rng.choice(["ok", "ok", "ok", "derate"]),
            sensors=SensorLog(
                accel_z=round(rng.uniform(-1.8, 2.4), 3),
                rms_vibration=round(rng.uniform(0.2, 4.8), 3),
                ir_reflectance=round(rng.uniform(0.1, 0.9), 3),
                depth_mm=round(depth, 2),
                surface_class=severity,
            ),
            severity=severity,
        )
        ingest_event(db, payload)

        # Extra nearby hits so clustering / heatmap has density
        if severity == "critical" and idx % 3 == 0:
            nearby = payload.model_copy(
                update={
                    "event_id": f"demo-pune-edge-{uuid.uuid4().hex[:12]}",
                    "timestamp": ts + timedelta(minutes=rng.randint(8, 90)),
                    "lon": lon + rng.uniform(-0.00018, 0.00018),
                    "lat": lat + rng.uniform(-0.00018, 0.00018),
                }
            )
            ingest_event(db, nearby)
